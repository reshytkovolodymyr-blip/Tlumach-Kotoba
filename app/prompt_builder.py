"""
prompt_builder.py
------------------
Формує готовий текстовий промпт для зовнішнього AI (ChatGPT тощо) на
основі мови вивчення, рівня та теми, обраних користувачем у майстрі
створення уроку (wizard.py).

Це НЕ звернення до жодного API — просто текст, який користувач сам
копіює й вставляє у свій AI-чат. Формат промпту навмисно узгоджений
із тим, що розпізнає parser.py ("Ім'я: репліка" + список фраз з
перекладом через " - ").

Ця версія промпту суворіша за попередню — доданий явний бриф вимог
(чергування спікерів, логічний зв'язок реплік, природне завершення,
явна заборона на вигадані фрази) і секція самоперевірки перед
відповіддю AI, а не лише перелік вимог. Це усталений прийом
промпт-інжинірингу: коли модель сама звіряє власну відповідь із
чек-листом перед відправкою, дотримання формату помітно надійніше.

КРИТИЧНО: список ключових фраз з перекладом — ЄДИНЕ джерело фраз для
режиму "Ключові фрази". Парсер не має власного автовиділення
"здогадкою" (регекс-fallback прибрано, воно працювало лише для
англійської і вгадувало, а не аналізувало). Тому цей промпт
зобов'язаний вимагати список фраз явно й у точному форматі — інакше
цей режим лишиться без матеріалу.
"""

from __future__ import annotations

from .languages import get_language

# Природна форма прикметника для українського речення промпту —
# окремо від lang.label, який призначений для GUI (може містити
# рідний скрипт мови, напр. "Japanese (日本語)").
_ADVERB = {
    "english": "англійською",
    "japanese": "японською",
    "french": "французькою",
    "spanish": "іспанською",
}

# Назва шкали рівнів — рівні мов вивчення НЕ всі за CEFR: японська
# використовує JLPT (N5-N1), решта — CEFR (A2-C1). Помилково написати
# "рівень N5 за CEFR" було б безглуздо, тому явно розрізняємо.
_LEVEL_SCALE_NAME = {
    "english": "CEFR",
    "french": "CEFR",
    "spanish": "CEFR",
    "japanese": "JLPT",
}

MIN_LINES = 10
MAX_LINES = 12
MIN_PHRASES = 5
MAX_PHRASES = 8


def build_prompt(language_code: str, level: str, topic: str) -> str:
    lang = get_language(language_code)
    topic = topic.strip() or "довільна повсякденна тема"
    level = level or lang.levels[0]
    adverb = _ADVERB.get(language_code, f"{lang.label} мовою")
    scale = _LEVEL_SCALE_NAME.get(language_code, "CEFR")

    extra_notes = ""
    if lang.needs_romaji:
        extra_notes = (
            "- Репліки пиши природним текстом (kanji/kana), без фуригани "
            "в дужках і без ромадзі — застосунок додає романізацію сам.\n"
        )

    return (
        f'Створи природний, логічно завершений діалог {adverb} рівня '
        f'{level} за шкалою {scale} на тему "{topic}".\n\n'
        "СУВОРО дотримуйся всіх вимог нижче. Не додавай жодного тексту, "
        "крім діалогу та списку ключових фраз.\n\n"
        "ФОРМАТ ВІДПОВІДІ:\n\n"
        "Ім'я1: репліка\n"
        "Ім'я2: репліка\n"
        "Ім'я1: репліка\n"
        "Ім'я2: репліка\n"
        "...\n\n"
        "Після останньої репліки залиш рівно один порожній рядок, а "
        "потім наведи список ключових фраз.\n\n"
        "ВИМОГИ ДО ДІАЛОГУ:\n\n"
        f"- Мова: {lang.label}.\n"
        f"- Рівень: {level} за шкалою {scale}.\n"
        f"- Тема: {topic}.\n"
        "- Рівно два спікери з природними для цієї мови іменами.\n"
        f"- Від {MIN_LINES} до {MAX_LINES} реплік загалом.\n"
        "- Спікери повинні чергуватися: кожна наступна репліка належить "
        "іншому спікеру.\n"
        "- Кожна репліка має починатися з імені спікера, двокрапки та "
        "пробілу.\n"
        "- Кожна репліка повинна бути на окремому рядку.\n"
        f"{extra_notes}"
        "- Діалог має звучати як реальна повсякденна розмова, а не як "
        "перелік завчених фраз.\n"
        "- Репліки мають бути логічно пов'язані між собою — кожна "
        "наступна репліка має бути природним продовженням попередньої.\n"
        "- Заверши діалог природно, щоб розмова мала зрозумілий кінець.\n\n"
        "ВИМОГИ ДО СПИСКУ КЛЮЧОВИХ ФРАЗ:\n\n"
        f"- Наведи від {MIN_PHRASES} до {MAX_PHRASES} ключових фраз, "
        "узятих безпосередньо з діалогу.\n"
        "- Це єдине джерело фраз для програми, тому список обов'язковий.\n"
        "- Обирай корисні для повсякденного спілкування словосполучення, "
        "які учень зможе використовувати в інших ситуаціях.\n"
        f"- Кожна фраза має бути {adverb} та супроводжуватися точним "
        "перекладом українською.\n"
        "- Переклад обов'язково має бути українською кирилицею.\n"
        "- Кожна фраза повинна бути на окремому рядку.\n"
        "- Дотримуйся точного формату кожного рядка:\n\n"
        "  фраза - переклад українською\n\n"
        "- Використовуй лише один дефіс із пробілами навколо нього як "
        "роздільник: -\n"
        "- Не додавай нумерацію, приклади, пояснення, примітки чи інші "
        "символи до рядків фраз.\n"
        "- Не додавай фраз, яких немає в діалозі.\n\n"
        "СУВОРО ЗАБОРОНЕНО:\n\n"
        "- Додавати заголовки, вступ, пояснення, висновки або коментарі.\n"
        "- Використовувати Markdown, зірочки, маркери списків чи "
        "нумерацію.\n"
        "- Додавати порожні рядки між репліками діалогу.\n"
        "- Додавати більше одного порожнього рядка між діалогом і "
        "списком фраз.\n"
        "- Додавати будь-який текст після останньої ключової фрази.\n\n"
        "ПЕРЕД ВІДПРАВЛЕННЯМ ПЕРЕВІР:\n\n"
        "1. У діалозі рівно два спікери.\n"
        f"2. Є від {MIN_LINES} до {MAX_LINES} реплік, і вони чергуються.\n"
        "3. Кожна репліка займає окремий рядок.\n"
        "4. Після діалогу є рівно один порожній рядок.\n"
        f"5. Є від {MIN_PHRASES} до {MAX_PHRASES} ключових фраз, усі "
        "взяті з діалогу.\n"
        "6. Кожен рядок фраз має формат «фраза - переклад українською».\n"
        "7. Немає жодного зайвого тексту чи оформлення."
    )
